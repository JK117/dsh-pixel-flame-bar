import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const css = readFileSync(new URL("src/lightbar.css", root), "utf8");
const flame = readFileSync(new URL("src/flame.js", root), "utf8");
const template = readFileSync(new URL("src/client.js", root), "utf8");
const cssMarker = "__LIGHTBAR_CSS_JSON__";
const flameMarker = "/*__FLAME_RENDERER__*/";

if (!template.includes(cssMarker)) {
  throw new Error(`src/client.js is missing the ${cssMarker} marker`);
}
if (!template.includes(flameMarker)) {
  throw new Error(`src/client.js is missing the ${flameMarker} marker`);
}

const output =
  "/* Generated by scripts/build.mjs — edit src/client.js, src/lightbar.css and src/flame.js. */\n" +
  template
    .replace(cssMarker, () => JSON.stringify(css))
    .replace(flameMarker, () => flame);

writeFileSync(new URL("lib/client.js", root), output);
console.log(
  `built lib/client.js (${Buffer.byteLength(output)} bytes) from ${fileURLToPath(
    new URL("src/lightbar.css", root),
  )} + src/flame.js`,
);
